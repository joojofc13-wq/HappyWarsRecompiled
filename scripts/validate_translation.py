"""Gate native compilation on source audits, caching only an exact content match."""
import hashlib
import json
import subprocess
import sys
from analyze import ROOT

if __name__=='__main__':
    sources=sorted((ROOT/'generated/default').glob('*.cpp'))
    if not sources:
        raise SystemExit('No generated translation to validate')
    digest=hashlib.sha256()
    for path in sources+[ROOT/'scripts/audit_codegen.py',ROOT/'scripts/audit_labels.py']:
        digest.update(path.name.encode())
        digest.update(hashlib.sha256(path.read_bytes()).digest())
    fingerprint=digest.hexdigest()
    cache=ROOT/'logs/translation-validation.json'
    prior=json.loads(cache.read_text()) if cache.exists() else {}
    if prior.get('passed') and prior.get('source_fingerprint')==fingerprint:
        print('Translation audits passed for these exact generated bytes (cached)')
        raise SystemExit(0)
    cache.write_text(json.dumps(dict(source_fingerprint=fingerprint,passed=False),indent=2),encoding='utf-8')
    for script in ('audit_labels.py','audit_codegen.py'):
        subprocess.run([sys.executable,str(ROOT/'scripts'/script)],cwd=ROOT,check=True)
    cache.write_text(json.dumps(dict(source_fingerprint=fingerprint,passed=True,
        scope='No missing C++ labels or explicit translation traps found; does not prove gameplay'),indent=2),encoding='utf-8')
